            for hex in parts[1].split(separator: " ") {
                if let value = UInt32(hex, radix: 16), let scalar = Unicode.Scalar(value) { scalars.append(scalar) }
            }
            table[String(parts[0])] = String(scalars)
        }
        return table
    }()

