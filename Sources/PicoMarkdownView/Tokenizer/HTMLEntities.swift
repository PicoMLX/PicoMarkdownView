/// HTML5 named character references (`&amp;`, `&ClockwiseContourIntegral;`),
/// which CommonMark decodes in text, link destinations and titles, and
/// fenced code info strings. Generated from the WHATWG list (via Python's
/// `html.entities.html5`), names with their trailing semicolon only. The
/// table is a string parsed on first use: a dictionary literal this size
/// is slow to type-check.
enum HTMLEntities {
    /// The replacement for `&name;`, or `nil` when `name` is not defined.
    static func named(_ name: Substring) -> String? {
        table[String(name)]
    }

    /// The longest entity name, which bounds how long an `&` may wait.
    static let maximumNameLength = 32

