    /// The character a numeric reference (`&#35;`, `&#x22;`) stands for:
    /// zero, surrogates and values past U+10FFFF become U+FFFD.
    static func numeric(_ value: UInt32) -> String {
        guard value != 0, let scalar = Unicode.Scalar(value) else { return "\u{FFFD}" }
        return String(Character(scalar))
    }

    enum Scan {
        /// A complete reference: what it stands for, and where it ends.
        case reference(String, end: String.Index)
        /// The text ends inside what may still become a reference.
        case partial
        case none
    }

    /// The character reference at `start`, which holds `&`: `&name;` for a
    /// defined name, `&#` and 1–7 decimal digits, or `&#x` and 1–6 hex
    /// digits, then `;` (CommonMark).
    static func scan(_ text: Substring, at start: String.Index) -> Scan {
        let scalars = text.unicodeScalars
        let end = text.endIndex
        var cursor = scalars.index(after: start)
        guard cursor < end else { return .partial }
        if scalars[cursor] == "#" {
            cursor = scalars.index(after: cursor)
            guard cursor < end else { return .partial }
            let hex = scalars[cursor] == "x" || scalars[cursor] == "X"
            if hex {
                cursor = scalars.index(after: cursor)
                guard cursor < end else { return .partial }
            }
            let radix: UInt32 = hex ? 16 : 10
            var value: UInt32 = 0
            var digits = 0
            while cursor < end, let digit = Character(scalars[cursor]).hexDigitValue, UInt32(digit) < radix {
                digits += 1
                if digits > (hex ? 6 : 7) { return .none }
                value = value * radix + UInt32(digit)
                cursor = scalars.index(after: cursor)
            }
            guard cursor < end else { return .partial }
            guard digits > 0, scalars[cursor] == ";" else { return .none }
            return .reference(numeric(value), end: scalars.index(after: cursor))
        }
        let nameStart = cursor
        guard scalars[cursor].isASCII, scalars[cursor].properties.isAlphabetic else { return .none }
        var length = 0
        while cursor < end, scalars[cursor].isASCII, scalars[cursor].properties.isAlphabetic || ("0"..."9").contains(scalars[cursor]) {
            length += 1
            if length > maximumNameLength { return .none }
            cursor = scalars.index(after: cursor)
        }
        guard cursor < end else { return .partial }
        guard scalars[cursor] == ";", let replacement = named(text[nameStart..<cursor]) else { return .none }
        return .reference(replacement, end: scalars.index(after: cursor))
    }

    /// `text` with backslash escapes of ASCII punctuation and character
    /// references resolved, as in link destinations, titles and fenced code
    /// info strings. An escaped `&` starts no reference.
    static func unescaping(_ text: Substring) -> String {
        guard text.contains("\\") || text.contains("&") else { return String(text) }
        let scalars = text.unicodeScalars
        var result = String.UnicodeScalarView()
        var cursor = text.startIndex
        while cursor < text.endIndex {
            let scalar = scalars[cursor]
            let next = scalars.index(after: cursor)
            if scalar == "\\", next < text.endIndex, scalars[next].isASCII,
               "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~".unicodeScalars.contains(scalars[next]) {
                result.append(scalars[next])
                cursor = scalars.index(after: next)
                continue
            }
            if scalar == "&", case .reference(let replacement, let end) = scan(text, at: cursor) {
                result.append(contentsOf: replacement.unicodeScalars)
                cursor = end
                continue
            }
            result.append(scalar)
            cursor = next
        }
        return String(result)
    }
